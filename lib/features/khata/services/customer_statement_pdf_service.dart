import 'dart:io';
import 'dart:typed_data';
import 'package:path_provider/path_provider.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:share_plus/share_plus.dart';
import '../../statements/models/customer_statement.dart';
import '../../statements/models/statement_entry.dart';

class CustomerStatementPdfService {
  static const PdfColor _primaryGreen = PdfColor(0.08, 0.49, 0.39);
  static const PdfColor _lightGreen = PdfColor(0.91, 0.97, 0.94);
  static const PdfColor _darkText = PdfColor(0.12, 0.16, 0.14);
  static const PdfColor _mutedText = PdfColor(0.42, 0.46, 0.44);
  static const PdfColor _borderColor = PdfColor(0.87, 0.90, 0.88);

  Future<Uint8List> generateStatement(CustomerStatement statement) async {
    final document = pw.Document();

    final entries = statement.entries.toList()
      ..sort((a, b) {
        final result = a.date.compareTo(b.date);
        return result != 0
            ? result
            : a.transactionId.compareTo(b.transactionId);
      });

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        header: _buildHeader,
        footer: _buildFooter,
        build: (context) => [
          pw.SizedBox(height: 20),
          pw.Text(
            'CUSTOMER STATEMENT',
            style: pw.TextStyle(
              color: _primaryGreen,
              fontSize: 19,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
          pw.SizedBox(height: 6),
          pw.Text(
            'Period: ${_formatDate(statement.startDate)} - '
            '${_formatDate(statement.endDate)}',
            style: const pw.TextStyle(color: _mutedText, fontSize: 10),
          ),
          pw.SizedBox(height: 18),
          _customerCard(statement),
          pw.SizedBox(height: 18),
          _balanceSummary(statement),
          pw.SizedBox(height: 22),
          _sectionTitle('TRANSACTION HISTORY'),
          pw.SizedBox(height: 10),
          if (entries.isEmpty)
            pw.Container(
              padding: const pw.EdgeInsets.all(20),
              alignment: pw.Alignment.center,
              decoration: pw.BoxDecoration(
                border: pw.Border.all(color: _borderColor),
                borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
              ),
              child: pw.Text(
                'No transactions found for this period.',
                style: const pw.TextStyle(color: _mutedText, fontSize: 10),
              ),
            )
          else
            _transactionTable(entries),
          pw.SizedBox(height: 20),
          _closingBalanceCard(statement),
          pw.SizedBox(height: 18),
          pw.Container(
            padding: const pw.EdgeInsets.all(12),
            decoration: pw.BoxDecoration(
              color: _lightGreen,
              borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
            ),
            child: pw.Text(
              'This statement was generated by DigiKhata from the '
              'recorded customer transactions for the selected period.',
              style: const pw.TextStyle(color: _mutedText, fontSize: 9),
            ),
          ),
        ],
      ),
    );

    return document.save();
  }

  Future<void> previewStatement(CustomerStatement statement) async {
    final bytes = await generateStatement(statement);

    await Printing.layoutPdf(
      onLayout: (_) async => bytes,
      name: 'DigiKhata_Statement_${_safeFileName(statement.customerName)}.pdf',
    );
  }

  /// Generates the statement PDF and opens the system share sheet.
  Future<void> shareStatement(CustomerStatement statement) async {
    final bytes = await generateStatement(statement);

    final fileName =
        'DigiKhata_Statement_${_safeFileName(statement.customerName)}.pdf';

    final directory = await getTemporaryDirectory();
    final file = File('${directory.path}/$fileName');

    await file.writeAsBytes(bytes, flush: true);

    await SharePlus.instance.share(
      ShareParams(
        files: [XFile(file.path, mimeType: 'application/pdf', name: fileName)],
        subject: 'DigiKhata Customer Statement - ${statement.customerName}',
        text: 'Customer statement for ${statement.customerName}.',
      ),
    );
  }

  pw.Widget _buildHeader(pw.Context context) {
    return pw.Container(
      padding: const pw.EdgeInsets.only(bottom: 12),
      decoration: const pw.BoxDecoration(
        border: pw.Border(bottom: pw.BorderSide(color: _borderColor)),
      ),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(
            'DIGIKHATA',
            style: pw.TextStyle(
              color: _primaryGreen,
              fontSize: 17,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
          pw.Text(
            'Customer Account Report',
            style: const pw.TextStyle(color: _mutedText, fontSize: 9),
          ),
        ],
      ),
    );
  }

  pw.Widget _buildFooter(pw.Context context) {
    return pw.Container(
      padding: const pw.EdgeInsets.only(top: 10),
      decoration: const pw.BoxDecoration(
        border: pw.Border(top: pw.BorderSide(color: _borderColor)),
      ),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(
            'Generated by DigiKhata',
            style: const pw.TextStyle(color: _mutedText, fontSize: 8),
          ),
          pw.Text(
            'Page ${context.pageNumber} of ${context.pagesCount}',
            style: const pw.TextStyle(color: _mutedText, fontSize: 8),
          ),
        ],
      ),
    );
  }

  pw.Widget _customerCard(CustomerStatement statement) {
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.all(16),
      decoration: pw.BoxDecoration(
        color: _lightGreen,
        borderRadius: const pw.BorderRadius.all(pw.Radius.circular(10)),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          _sectionTitle('CUSTOMER DETAILS'),
          pw.SizedBox(height: 10),
          pw.Text(
            statement.customerName,
            style: pw.TextStyle(
              color: _darkText,
              fontSize: 15,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
          pw.SizedBox(height: 5),
          pw.Text(
            'Customer ID: ${statement.customerId}',
            style: const pw.TextStyle(color: _mutedText, fontSize: 8),
          ),
        ],
      ),
    );
  }

  pw.Widget _balanceSummary(CustomerStatement statement) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        _sectionTitle('PERIOD SUMMARY'),
        pw.SizedBox(height: 10),
        pw.Table(
          border: pw.TableBorder.all(color: _borderColor, width: 0.6),
          columnWidths: const {
            0: pw.FlexColumnWidth(1),
            1: pw.FlexColumnWidth(1),
          },
          children: [
            _summaryRow(
              'Opening Balance',
              _money(statement.openingBalance),
              'Credit Added',
              _money(statement.totalCredit),
            ),
            _summaryRow(
              'Payments Received',
              _money(statement.totalPayments),
              'Closing Balance',
              _money(statement.closingBalance),
            ),
          ],
        ),
      ],
    );
  }

  pw.TableRow _summaryRow(
    String firstLabel,
    String firstValue,
    String secondLabel,
    String secondValue,
  ) {
    return pw.TableRow(
      children: [
        _summaryCell(firstLabel, firstValue),
        _summaryCell(secondLabel, secondValue),
      ],
    );
  }

  pw.Widget _summaryCell(String label, String value) {
    return pw.Padding(
      padding: const pw.EdgeInsets.all(10),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            label,
            style: const pw.TextStyle(color: _mutedText, fontSize: 9),
          ),
          pw.SizedBox(height: 5),
          pw.Text(
            'Rs $value',
            style: pw.TextStyle(
              color: _darkText,
              fontSize: 11,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
        ],
      ),
    );
  }

  pw.Widget _transactionTable(List<StatementEntry> entries) {
    return pw.TableHelper.fromTextArray(
      headers: const [
        'Date',
        'Description',
        'Type',
        'Credit (Rs)',
        'Payment (Rs)',
      ],
      data: entries.map((entry) {
        return [
          _formatDate(entry.date),
          (entry.description?.trim().isNotEmpty ?? false)
              ? entry.description!.trim()
              : '-',
          entry.isCredit ? 'Credit' : 'Payment',
          entry.isCredit ? _money(entry.amount) : '-',
          entry.isPayment ? _money(entry.amount) : '-',
        ];
      }).toList(),
      headerStyle: pw.TextStyle(
        color: PdfColors.white,
        fontSize: 8,
        fontWeight: pw.FontWeight.bold,
      ),
      headerDecoration: const pw.BoxDecoration(color: _primaryGreen),
      cellStyle: const pw.TextStyle(color: _darkText, fontSize: 8),
      cellAlignment: pw.Alignment.centerLeft,
      cellPadding: const pw.EdgeInsets.symmetric(horizontal: 5, vertical: 7),
      border: pw.TableBorder.all(color: _borderColor, width: 0.5),
      columnWidths: const {
        0: pw.FlexColumnWidth(1.05),
        1: pw.FlexColumnWidth(2),
        2: pw.FlexColumnWidth(1),
        3: pw.FlexColumnWidth(1.15),
        4: pw.FlexColumnWidth(1.15),
      },
      oddRowDecoration: const pw.BoxDecoration(color: PdfColors.grey100),
    );
  }

  pw.Widget _closingBalanceCard(CustomerStatement statement) {
    final balance = statement.closingBalance;
    final label = balance > 0
        ? 'AMOUNT OUTSTANDING'
        : balance < 0
        ? 'CUSTOMER ADVANCE'
        : 'BALANCE SETTLED';

    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.all(18),
      decoration: pw.BoxDecoration(
        color: _lightGreen,
        border: pw.Border.all(color: _primaryGreen),
        borderRadius: const pw.BorderRadius.all(pw.Radius.circular(10)),
      ),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Expanded(
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(
                  label,
                  style: pw.TextStyle(
                    color: _primaryGreen,
                    fontSize: 10,
                    fontWeight: pw.FontWeight.bold,
                  ),
                ),
                pw.SizedBox(height: 6),
                pw.Text(
                  'Closing balance for selected period',
                  style: const pw.TextStyle(color: _mutedText, fontSize: 8),
                ),
              ],
            ),
          ),
          pw.SizedBox(width: 12),
          pw.Text(
            'Rs ${_money(balance.abs())}',
            style: pw.TextStyle(
              color: _primaryGreen,
              fontSize: 17,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
        ],
      ),
    );
  }

  pw.Widget _sectionTitle(String title) {
    return pw.Text(
      title,
      style: pw.TextStyle(
        color: _primaryGreen,
        fontSize: 10,
        fontWeight: pw.FontWeight.bold,
      ),
    );
  }

  String _formatDate(DateTime date) {
    final local = date.toLocal();
    return '${local.day.toString().padLeft(2, '0')}/'
        '${local.month.toString().padLeft(2, '0')}/'
        '${local.year}';
  }

  String _money(double amount) => amount.toStringAsFixed(2);

  String _safeFileName(String value) {
    final safe = value
        .trim()
        .replaceAll(RegExp(r'[^a-zA-Z0-9_-]+'), '_')
        .replaceAll(RegExp(r'_+'), '_');

    return safe.isEmpty ? 'Customer' : safe;
  }
}
